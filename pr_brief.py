#!/usr/bin/env python3
"""UnvibeCode PR Brief (prototype).

Turns an UnvibeCode results folder + a list of changed files into one
Markdown comment for a pull request. Standard library only.

Usage:
  python pr_brief.py --results <unvibecode-analysis-folder> --changed src/a.py src/b.py
  git diff --name-only origin/main... | python pr_brief.py --results <folder> --changed -
"""
import argparse, collections, glob, html, json, os, re, sys, zipfile

BRAND = "Generated by UnvibeCode"


def load_bundle(results):
    """Read chunks/connections from the context ZIP (or an extracted folder)."""
    zips = glob.glob(os.path.join(results, "*repository-context.zip"))
    def read(name):
        if zips:
            with zipfile.ZipFile(zips[0]) as z:
                return z.read(name).decode("utf-8").splitlines()
        with open(os.path.join(results, name), encoding="utf-8") as f:
            return f.read().splitlines()
    chunks = [json.loads(l) for l in read("chunks.jsonl") if l.strip()]
    conns = [json.loads(l) for l in read("connections.jsonl") if l.strip()]
    return chunks, conns


def load_workflows(results):
    """Map workflow title -> set of files, from the report's 'Implementation references'."""
    paths = glob.glob(os.path.join(results, "report-support", "business-workflows.html"))
    if not paths:
        return {}
    t = open(paths[0], encoding="utf-8", errors="ignore").read()
    t = re.sub(r"<script.*?</script>|<style.*?</style>", "", t, flags=re.S)
    t = html.unescape(re.sub(r"<[^>]+>", " ", t))
    t = re.sub(r"\s+", " ", t)
    out = {}
    for m in re.finditer(r"Workflow \d+ (.+?) What this workflow does(.*?)(?=Workflow area \d|Workflow \d+ |Continue your review|$)", t):
        title, body = m.group(1).strip(), m.group(2)
        files = set(re.findall(r"((?:[\w.\-]+/)+[\w.\-]+\.\w+) · lines", body))
        if files:
            out[title] = files
    return out


def build(results, changed):
    chunks, conns = load_bundle(results)
    known = {c["file"] for c in chunks}
    changed = [c for c in dict.fromkeys(changed) if c]
    analysed = [c for c in changed if c in known]
    skipped = [c for c in changed if c not in known]

    # Direct neighbours, both directions, counted by number of links.
    dependents = collections.Counter()   # files that import a changed file
    dependencies = collections.Counter() # files a changed file imports
    for c in conns:
        s, t = c["source_file"], c["target_file"]
        if s == t:
            continue
        if t in analysed and s not in analysed:
            dependents[s] += 1
        if s in analysed and t not in analysed:
            dependencies[t] += 1

    # Which workflows touch these files?
    workflows = load_workflows(results)
    touched = [w for w, fs in workflows.items() if fs & set(analysed)]

    # Simple, explainable risk label (heuristic, not a security verdict).
    n_dep = len(dependents)
    score = n_dep + 3 * len(touched)
    prod_changed = [c for c in analysed if not re.search(r"(^|/)(tests?|docs?|examples?)/", c)]
    if not prod_changed:
        label = "low-risk"
    elif score >= 12:
        label = "high-risk"
    elif score >= 4:
        label = "medium-risk"
    else:
        label = "low-risk"

    L = [f"## UnvibeCode PR Brief  `unvibecode: {label}`", ""]
    L.append(f"{len(changed)} file(s) changed, {len(analysed)} found in the Connected Code Map.")
    L.append("")
    L.append("**Business workflows touched**")
    if touched:
        L += [f"- {w}" for w in touched]
    else:
        L.append("- None of the mapped workflows reference these files.")
    L.append("")
    L.append("**Review these files first** (they depend on the changed code)")
    if dependents:
        L += [f"- `{f}` ({n} link{'s' if n != 1 else ''})" for f, n in dependents.most_common(8)]
    else:
        L.append("- No other file depends on the changed code.")
    L.append("")
    L.append("**The changed code relies on**")
    if dependencies:
        L += [f"- `{f}`" for f, _ in dependencies.most_common(5)]
    else:
        L.append("- No mapped dependencies.")
    if skipped:
        L += ["", f"_Not in the map (new, unsupported or skipped): {', '.join('`'+s+'`' for s in skipped[:6])}_"]
    L += ["", f"_Risk label rule: dependents + 3 x workflows touched; docs/tests-only = low. {BRAND}._"]
    return "\n".join(L), label


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results", required=True, help="UnvibeCode analysis folder")
    ap.add_argument("--changed", nargs="+", required=True, help="changed files, or - to read from stdin")
    a = ap.parse_args()
    changed = sys.stdin.read().split() if a.changed == ["-"] else a.changed
    text, label = build(a.results, changed)
    print(text)


if __name__ == "__main__":
    main()
