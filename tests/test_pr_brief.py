"""Run with: python -m unittest discover tests"""
import os, sys, unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import pr_brief  # noqa: E402

SAMPLE = os.path.join(os.path.dirname(HERE), "examples", "flask-sample.json")


class PrBriefTest(unittest.TestCase):
    def test_core_file_is_high_risk(self):
        text, label = pr_brief.build(SAMPLE, ["src/flask/helpers.py"])
        self.assertEqual(label, "high-risk")
        self.assertIn("`src/flask/__init__.py` (11 links)", text)

    def test_config_change_names_its_workflow(self):
        text, label = pr_brief.build(SAMPLE, ["src/flask/config.py"])
        self.assertIn("Load application configuration", text)

    def test_docs_only_change_is_low_risk(self):
        text, label = pr_brief.build(SAMPLE, ["docs/conf.py", "README.md"])
        self.assertEqual(label, "low-risk")
        self.assertIn("Not in the map", text)  # README.md is not a mapped source file

    def test_comment_is_branded(self):
        text, _ = pr_brief.build(SAMPLE, ["src/flask/app.py"])
        self.assertIn("Generated by UnvibeCode", text)


if __name__ == "__main__":
    unittest.main()
